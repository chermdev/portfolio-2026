async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:4173';
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const result = name => page.getByRole('region', {name});
  const select = async (name, option) => { await page.getByRole('combobox', {name, exact:true}).click(); await page.getByRole('option', {name:option, exact:true}).click(); };
  await page.goto(base + '/tools/stripe-calculator');
  await page.getByRole('spinbutton', {name:/Payment amount/}).fill('1000');
  assert((await result('Stripe fee result').innerText()).includes('954.76'), 'MXN preset');
  await page.getByRole('radio', {name:'I want to receive',exact:true}).click();
  await page.getByRole('spinbutton', {name:/Desired remaining/}).fill('1000');
  assert((await result('Stripe fee result').innerText()).includes('1,047.21'), 'Reverse fees');
  await select('Account & currency preset', 'United States · USD');
  await page.getByRole('radio', {name:'I charge',exact:true}).click();
  await page.getByRole('spinbutton', {name:/Payment amount/}).fill('1000');
  assert((await result('Stripe fee result').innerText()).includes('970.70'), 'USD preset');
  await select('Radar plan preset', 'Radar Plus');
  assert((await result('Stripe fee result').innerText()).includes('970.63'), 'USD Radar Plus');
  await page.getByRole('spinbutton', {name:/Radar per screened/}).fill('1.25');
  assert((await result('Stripe fee result').innerText()).includes('969.45'), 'Custom Radar');
  await page.getByRole('switch', {name:'International card',exact:true}).click();
  assert(await page.getByRole('spinbutton', {name:/International card surcharge/}).isVisible(), 'International field');
  await page.getByRole('spinbutton', {name:/Processing rate/}).fill('100');
  assert((await result('Stripe fee result').innerText()).includes('Check your numbers'), 'Invalid rate');
  await page.getByRole('button', {name:'Reset rates'}).click();
  assert(!(await result('Stripe fee result').innerText()).includes('Check your numbers'), 'Reset recovery');
  await page.screenshot({path:'/Users/chsh/repos/portfolio-2026/artifacts/qa/stripe-desktop.png',fullPage:true});
  await page.goto(base+'/tools/auto-loan-calculator');
  await page.getByRole('spinbutton', {name:/Vehicle price/}).fill('120000');
  await page.getByRole('spinbutton', {name:/Annual interest rate/}).fill('0');
  await page.getByRole('spinbutton', {name:/Term in months/}).fill('12');
  assert((await result('Loan result').innerText()).includes('8,000.00'), 'Zero-interest auto');
  await page.getByRole('radio', {name:'Purchasing power',exact:true}).click();
  await page.getByRole('spinbutton', {name:/Monthly payment budget/}).fill('8000');
  assert((await result('Loan result').innerText()).includes('120,000.00'), 'Auto purchasing power');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', {name:'Download payment schedule'}).click();
  const download = await downloadPromise;
  await download.saveAs('/Users/chsh/repos/portfolio-2026/artifacts/qa/auto-schedule.csv');
  await page.goto(base+'/tools/mortgage-calculator');
  await page.getByRole('spinbutton', {name:/Home price/}).fill('1200000');
  await page.getByRole('spinbutton', {name:/Annual interest rate/}).fill('0');
  await page.getByRole('spinbutton', {name:/Term in months/}).fill('120');
  await page.getByRole('spinbutton', {name:/Down payment/}).fill('10');
  assert((await result('Loan result').innerText()).includes('9,000.00'), 'Mortgage monthly');
  await page.getByRole('radio', {name:'Purchasing power',exact:true}).click();
  await page.getByRole('spinbutton', {name:/Monthly payment budget/}).fill('9000');
  assert((await result('Loan result').innerText()).includes('1,200,000.00'), 'Mortgage inverse');
  await page.getByRole('spinbutton', {name:/Down payment/}).fill('12');
  assert((await result('Loan result').innerText()).includes('increments of 5'), 'Mortgage step validation');
  await page.getByRole('spinbutton', {name:/Down payment/}).fill('10');
  await page.getByRole('button',{name:'View payment schedule'}).click();
  assert(await page.getByRole('table').isVisible(), 'Amortization table');
  assert(errors.length === 0, 'Browser errors: '+errors.join(';'));
  console.log('PASS: Stripe presets/custom/inverse/validation/reset; auto & mortgage payment/power; mortgage steps; CSV export; amortization table.');
}
